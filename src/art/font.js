// ── 3×5 bitmap font for in-canvas text (jumbotron, callouts) ──
// Each glyph is 5 rows of 3 bits. Unknown chars render as blank.

export const GLYPHS = {
  A: "010101111101101", B: "110101110101110", C: "011100100100011", D: "110101101101110",
  E: "111100110100111", F: "111100110100100", G: "011100101101011", H: "101101111101101",
  I: "111010010010111", J: "001001001101010", K: "101101110101101", L: "100100100100111",
  M: "101111111101101", N: "110101101101101", O: "010101101101010", P: "110101110100100",
  Q: "010101101110011", R: "110101110101101", S: "011100010001110", T: "111010010010010",
  U: "101101101101111", V: "101101101101010", W: "101101111111101", X: "101101010101101",
  Y: "101101010010010", Z: "111001010100111",
  0: "111101101101111", 1: "010110010010111", 2: "110001010100111", 3: "110001010001110",
  4: "101101111001001", 5: "111100110001110", 6: "011100111101111", 7: "111001010010010",
  8: "111101111101111", 9: "111101111001110",
  "!": "010010010000010", "-": "000000111000000", ".": "000000000000010", ":": "000010000010000",
  "'": "010010000000000", "/": "001001010100100", " ": "000000000000000",
};

export const textWidth = (s) => (s.length ? s.length * 4 - 1 : 0);

// Draw text at (x, y) top-left in one color. Returns the width drawn.
export function drawText(ctx, s, x, y, color) {
  ctx.fillStyle = color;
  const str = String(s).toUpperCase();
  for (let i = 0; i < str.length; i++) {
    const g = GLYPHS[str[i]];
    if (!g) continue;
    for (let b = 0; b < 15; b++) if (g[b] === "1") ctx.fillRect(x + i * 4 + (b % 3), y + Math.floor(b / 3), 1, 1);
  }
  return textWidth(str);
}
