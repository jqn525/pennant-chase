// Merge each row's runs into single rects
const RECTS = Object.fromEntries(Object.entries(BITS).map(([k, rows]) => {
  const rects = [];
  rows.forEach((r, y) => {
    for (let x = 0; x < r.length;) {
      if (r[x] !== "#") { x++; continue; }
      let w = 0;
      while (r[x + w] === "#") w++;
      rects.push([x, y, w]);
      x += w;
    }
  });
  return [k, rects];
}));

const Px = ({ name, size, color }) => (
  <svg width={size} height={size} viewBox="0 0 12 12" fill={color} shapeRendering="crispEdges" aria-hidden="true">
    {RECTS[name].map(([x, y, w]) => <rect key={`${x}-${y}`} x={x} y={y} width={w} height={1} />)}
  </svg>
);

const icon = (name, dSize, dColor) => ({ size = dSize, color = dColor }) => <Px name={name} size={size} color={color} />;

